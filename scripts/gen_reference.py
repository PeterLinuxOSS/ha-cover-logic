"""Render docs/site/reference/fields.yaml into configuration.md."""

from pathlib import Path

import yaml

_ROOT = Path(__file__).parent.parent
_SRC = _ROOT / "docs/site/reference/fields.yaml"
_OUT = _ROOT / "docs/site/reference/configuration.md"
_TITLES = {
    "blinds": "blinds",
    "zones": "zones",
    "values_entity": "values (entity)",
    "values_slat_angle": "values (type: slat_angle)",
    "modes": "modes",
    "rules": "rules",
    "action": "rule `then`",
    "guards": "guards",
    "manual_detection": "manual_detection",
}
_HEADER = (
    "# Configuration reference\n\n<!-- Generated by scripts/gen_reference.py. Do not edit. -->\n"
)


def _cell(value) -> str:
    """Render one table cell: blank for unset, lowercase for a bool, `|` escaped, else as-is."""
    text = "" if value is None else str(value).lower() if isinstance(value, bool) else str(value)
    return text.replace("|", "\\|")


def render(fields: dict) -> str:
    """Render the parsed `fields.yaml` mapping into the reference page's Markdown text."""
    parts = [_HEADER]
    for section, title in _TITLES.items():
        parts.append(
            f"\n## {title}\n\n| Field | Type | Default | Range | Meaning |\n|---|---|---|---|---|\n"
        )
        for name, f in sorted(fields[section].items()):
            parts.append(
                f"| `{name}` | {_cell(f.get('type'))} | {_cell(f.get('default'))} "
                f"| {_cell(f.get('range'))} | {_cell(f.get('help'))} |\n"
            )
    return "".join(parts)


if __name__ == "__main__":
    _OUT.write_text(render(yaml.safe_load(_SRC.read_text())), encoding="utf-8")
